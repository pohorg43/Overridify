print_cli_help() {
    echo -e " ${C_BOLD}Usage:${C_RESET} overridify [command] [options]\n"
    echo -e " ${C_GREEN}Commands:${C_RESET}"
    echo -e "   ${C_YELLOW}(no arguments)${C_RESET}                    Launch interactive TUI interface"
    echo -e "   ${C_YELLOW}audit [subsystem|full] [-o [path]]${C_RESET} Audit subsystem (terminal or file export)"
    echo -e "   ${C_YELLOW}preset [id|all|reset|status|conflicts]${C_RESET} Manage rendering presets (vulkan, smooth, touch, gaming)"
    echo -e "   ${C_YELLOW}radar [--clean]${C_RESET}                   Scan system for junk properties"
    echo -e "   ${C_YELLOW}search <query>${C_RESET}                    Search properties in target binaries"
    echo -e "   ${C_YELLOW}export [subsystem|all] [path]${C_RESET}     Export subsystem or full report (default: /sdcard/...)"
    echo -e "   ${C_YELLOW}help, -h, --help${C_RESET}                  Show this help message\n"
}
